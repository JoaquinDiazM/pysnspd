UPSTREAM_REVISION = "5b6bd747f80016da5ccd51db73c110a8ecc6abf6"
UPSTREAM_URL = "https://github.com/qnngroup/proj-KE-solver"
NBN_RAW_SHA256 = "e94f11273e6c42b7c8fad978b78d119166e241bec1614ee77e4176906fa8f5df"
NBN_PUBLIC_SHA256 = "9aeea0948033d771deedae40da0cb4dc59fef80ac6ea41ac4d3a67b180efc610"
